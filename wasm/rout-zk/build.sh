#!/usr/bin/env bash
# Deterministic build of the ROUT anonymous booking engine (wasm/rout-zk),
# same rules as wasm/rout-opaque/build.sh (owner rule F.2).
#
#   wasm/rout-zk/build.sh            build with the pinned official toolchain,
#                                    write the .wasm and the embedded base64
#                                    module into src/ (then set zk-wasm-pin.ts)
#   wasm/rout-zk/build.sh --check    build in a clean target dir and fail
#                                    unless the SHA-384 equals the pin
#   wasm/rout-zk/build.sh --dev OUT  any rustc 1.95.0; writes OUT only, for the
#                                    *.engine.test.ts files (ROUT_ZK_DEV_WASM).
#                                    Never pinned, never committed.
#
# Fixed, imported linear memory of 32 pages (2 MiB, initial = maximum, 1 MiB
# stack first); no allocator is linked, so the module has no memory.grow.
set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(cd ../.. && pwd)"
RUSTC_PIN="rustc 1.95.0"
RUSTC_COMMIT_PIN="59807616e1fa2540724bfbac14d7976d7e4a3860"
LLVM_PIN="22.1.2"
OUT_DIR="$ROOT/src/lib/crypto-enclave/wasm"
PIN_FILE="$ROOT/src/lib/crypto-enclave/zk-wasm-pin.ts"
BYTES_FILE="$ROOT/src/lib/crypto-enclave/zk-wasm-bytes.ts"
MODE="${1:-}"

actual="$(rustc --version)"
case "$actual" in
  "$RUSTC_PIN "*) ;;
  *) echo "rustc pin mismatch: want $RUSTC_PIN, have $actual" >&2; exit 2 ;;
esac
verbose="$(rustc -vV)"
commit="$(sed -n 's/^commit-hash: //p' <<<"$verbose")"
llvm="$(sed -n 's/^LLVM version: //p' <<<"$verbose")"
if [[ "$MODE" != "--dev" ]] && [[ "$commit" != "$RUSTC_COMMIT_PIN" || "$llvm" != "$LLVM_PIN" ]]; then
  echo "rustc build mismatch: want commit $RUSTC_COMMIT_PIN with LLVM $LLVM_PIN (official rustup 1.95.0), have commit $commit with LLVM $llvm" >&2
  exit 2
fi
echo "toolchain $actual, LLVM $llvm"

TARGET_DIR="$(mktemp -d)"
trap 'rm -rf "$TARGET_DIR"' EXIT
export RUSTFLAGS="-C link-arg=--import-memory -C link-arg=--initial-memory=2097152 -C link-arg=--max-memory=2097152 -C link-arg=-zstack-size=1048576 --remap-path-prefix=${CARGO_HOME:-$HOME/.cargo}=/cargo --remap-path-prefix=$PWD=/rout-zk"
export SOURCE_DATE_EPOCH=0
CARGO_TARGET_DIR="$TARGET_DIR" cargo build --release --locked --lib --target wasm32-unknown-unknown
WASM="$TARGET_DIR/wasm32-unknown-unknown/release/rout_zk.wasm"
SHA384="$(sha384sum "$WASM" | cut -d' ' -f1)"
echo "sha384 $SHA384"

if [[ "$MODE" == "--dev" ]]; then
  cp "$WASM" "${2:?--dev needs an output path}"
  echo "wrote $2 (development build: not reproducible, never pin it)"
  exit 0
fi

if [[ "$MODE" == "--check" ]]; then
  PINNED="$(grep -oE '[0-9a-f]{96}' "$PIN_FILE" | head -1 || true)"
  if [[ -z "$PINNED" ]]; then echo "no pin in $PIN_FILE" >&2; exit 1; fi
  if [[ "$SHA384" != "$PINNED" ]]; then echo "reproducible build mismatch: pinned $PINNED" >&2; exit 1; fi
  cmp "$WASM" "$OUT_DIR/rout-zk.wasm"
  sed -n 's/^  "\([A-Za-z0-9+/=]*\)";$/\1/p' "$BYTES_FILE" | base64 -d | cmp - "$WASM"
  echo "reproducible: matches the pin, the committed module and its embedded base64 copy"
  exit 0
fi

mkdir -p "$OUT_DIR"
cp "$WASM" "$OUT_DIR/rout-zk.wasm"
{
  echo "// Generated by wasm/rout-zk/build.sh — do not edit. SHA-384 pinned in zk-wasm-pin.ts."
  printf 'export const ROUT_ZK_WASM_BASE64: string | null =\n  "%s";\n' "$(base64 -w0 "$WASM")"
} > "$BYTES_FILE"
echo "wrote $OUT_DIR/rout-zk.wasm and $BYTES_FILE; set zk-wasm-pin.ts to $SHA384 in the same change"
